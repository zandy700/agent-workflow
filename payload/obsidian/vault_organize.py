#!/usr/bin/env python3
"""Keep the Obsidian vault organized.

  vault_organize.py graph <repo-root> <repo-id>   graphify export → graphify/<id>/{communities,nodes/<repo folder>}
  vault_organize.py home                          regenerate Home.md + per-project "<id> Home" notes
  vault_organize.py migrate                       one-time: sort existing chats, park stray root files

Layout it maintains (see the vault's CLAUDE.md):
  Home.md                                  entry point, generated
  <id>/<id> Home.md                        project notebook index
  graphify/<id>/<id> Graph Overview.md     graph index; communities/ = hubs, nodes/<repo folder>/ = symbols
  chats/<tool>/<YYYY-MM>/                  code|codex|cursor|web; Claude sub-agent runs in chats/code/subagents/<YYYY-MM>/
"""
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import date
from pathlib import Path

from claude_to_obsidian import chat_dir

VAULT = Path(os.environ.get("OBSIDIAN_VAULT", Path.home() / "Obsidian Sync/ObsidianVault"))
SKIP = {"chats", "graphify", "templates", "knowledge", "_archive"}   # not projects
ZK = ["inbox", "fleeting", "permanent", "references", "logs"]
GENERATED = "<!-- generated by ~/Obsidian Sync/vault_organize.py; edits are overwritten -->"


def safe(s: str) -> str:
    return re.sub(r'[\\/:*?"<>|#^\[\]]', "-", s).strip()[:60] or "misc"


def front(text: str) -> dict:
    m = re.match(r"---\n(.*?)\n---", text, re.S)
    return {k.strip(): v.strip().strip('"') for k, _, v in (l.partition(":") for l in m.group(1).splitlines() if ":" in l and not l.startswith((" ", "-")))} if m else {}


# ── graphify notes ──────────────────────────────────────────────────────────
def organize_graph(src: Path, dest: Path, rid: str):
    notes = {f.name: f.read_text(encoding="utf-8") for f in src.glob("*.md")}
    plan, comms = {}, []          # filename → relative path in dest
    for name, text in notes.items():
        fm = front(text)
        if fm.get("type") == "community":
            title = re.sub(r"^_COMMUNITY_", "", name)[:-3]
            n = int(fm.get("members", 0) or 0)
            plan[name] = f"communities/{'' if n >= 5 else '_small/'}Community - {title}.md"
            comms.append((title, n))
        else:   # group symbols by where they live in the repo, not by (often 1-member) community
            parts = [safe(x).lstrip(".") for x in fm.get("source_file", "").split("/")[:-1][:2]]  # dot dirs are hidden in Obsidian
            plan[name] = "nodes/" + "/".join(x for x in parts if x) + ("/" if parts else "_root/") + name

    tmp = Path(tempfile.mkdtemp(dir=dest.parent))
    for name, text in notes.items():   # nothing links to hubs by filename, but keep it correct if it does
        text = re.sub(r"\[\[_COMMUNITY_", "[[Community - ", text)
        out = tmp / plan[name]
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")

    canvas = src / "graph.canvas"
    if canvas.exists():            # canvas nodes reference files by path
        d = json.loads(canvas.read_text(encoding="utf-8"))
        for n in d["nodes"]:
            if n.get("type") == "file":
                n["file"] = f"graphify/{rid}/" + plan.get(n["file"], n["file"])
        (tmp / "graph.canvas").write_text(json.dumps(d, indent=1), encoding="utf-8")

    big = sorted((c for c in comms if c[1] >= 5), key=lambda r: -r[1])
    rows = "\n".join(f"| [[Community - {t}]] | {m} |" for t, m in big)
    (tmp / f"{rid} Graph Overview.md").write_text(
        f"---\ntitle: \"{rid} Graph Overview\"\ntags: [graphify, {rid}]\ncreated: {date.today()}\nstatus: generated\ntype: index\n---\n"
        f"{GENERATED}\n# {rid} — code graph\n\nProject notebook: [[{rid} Home]] · all projects: [[Home]] · visual map: [[graph.canvas]]\n\n"
        f"{len(notes) - len(comms)} notes. `nodes/` mirrors the repo's folders; `communities/` holds the {len(big)} hubs with 5+ members "
        f"({len(comms) - len(big)} tiny ones are in `communities/_small/`).\n\n| Community | Members |\n|---|---|\n{rows}\n", encoding="utf-8")

    dest.mkdir(parents=True, exist_ok=True)
    keep = {".origin"}
    for old in dest.iterdir():     # dest is fully generated; only .origin survives
        if old.name not in keep:
            shutil.rmtree(old) if old.is_dir() else old.unlink()
    for new in tmp.iterdir():
        shutil.move(str(new), dest / new.name)
    tmp.rmdir()


def export_graph(root: Path, rid: str):
    with tempfile.TemporaryDirectory() as t:
        subprocess.run(["graphify", "export", "obsidian", "--dir", t], cwd=root, check=True, capture_output=True)
        organize_graph(Path(t), VAULT / "graphify" / rid, rid)
    (VAULT / "graphify" / rid / ".origin").write_text(str(root))
    write_homes()


# ── home notes ──────────────────────────────────────────────────────────────
def md_links(folder: Path, cap: int = 80) -> str:
    files = sorted(p for p in folder.rglob("*.md") if not any(x.startswith(".") for x in p.relative_to(folder).parts))
    return "\n".join(f"- [[{p.stem}]]" for p in files[:cap]) + (f"\n- … and {len(files) - cap} more" if len(files) > cap else "")


def project_dirs():
    return sorted(d for d in VAULT.iterdir() if d.is_dir() and not d.name.startswith((".", "_")) and d.name not in SKIP and d.name not in ZK)


def write_homes():
    projects = []
    for d in project_dirs():
        rid = d.name
        subs = sorted(s for s in d.iterdir() if s.is_dir() and not s.name.startswith("."))
        graph = f"- Code graph: [[{rid} Graph Overview]]\n" if (VAULT / "graphify" / rid / f"{rid} Graph Overview.md").exists() else ""
        sections = [f"\n### {s.name}\n{md_links(s)}" for s in subs if any(s.rglob("*.md"))]
        body = "".join(sections) or "\n_Empty notebook — add architecture, decisions and features notes here._"
        top = "\n".join(f"- [[{p.stem}]]" for p in sorted(d.glob("*.md")) if p.stem != f"{rid} Home")
        (d / f"{rid} Home.md").write_text(
            f"---\ntitle: \"{rid} Home\"\ntags: [project, {rid}]\nupdated: {date.today()}\nstatus: active\ntype: index\n---\n{GENERATED}\n"
            f"# {rid}\n\nBack to [[Home]]. Note organization: [[obsidian-organization]].\n\n{graph}{top}\n{body if sections or not top else ''}\n", encoding="utf-8")
        projects.append(rid)

    chats = ""
    for tool in ("code", "codex", "cursor", "web"):
        n = sum(1 for _ in (VAULT / "chats" / tool).rglob("*.md")) if (VAULT / "chats" / tool).exists() else 0
        chats += f"- `chats/{tool}/` — {n} chats\n"
    plist = "\n".join(f"- [[{p} Home]]" for p in projects)
    zk = " · ".join(f"`{z}/`" for z in ZK)
    (VAULT / "Home.md").write_text(
        f"---\ntitle: Home\ntags: [index]\nupdated: {date.today()}\nstatus: active\ntype: index\n---\n{GENERATED}\n# Vault home\n\n"
        f"## Projects\n{plist}\n\n## Chats (auto-synced, one folder per month)\n{chats}\n"
        f"## Knowledge base\n{zk}, `templates/`. Rules: see `CLAUDE.md`. Note organization: [[obsidian-organization]].\n\n"
        f"## Graphs\nEach project's code graph lives in `graphify/<id>/` — open its *Graph Overview*.\n", encoding="utf-8")


# ── chats ───────────────────────────────────────────────────────────────────
def migrate():
    for tool in ("code", "codex", "cursor", "web"):
        base = VAULT / "chats" / tool
        for f in list(base.glob("*.md")) if base.exists() else []:
            d = chat_dir(VAULT, tool, f.name)
            d.mkdir(parents=True, exist_ok=True)
            shutil.move(str(f), d / f.name)
    arch = VAULT / "_archive"
    for name in ("2026-08-28.md", "Untitled.base", "Untitled 1.base"):
        if (VAULT / name).exists():
            arch.mkdir(exist_ok=True)
            shutil.move(str(VAULT / name), arch / name)
    write_homes()


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "graph":
        export_graph(Path(sys.argv[2]), sys.argv[3])
    elif cmd == "home":
        write_homes()
    elif cmd == "migrate":
        migrate()
    else:
        sys.exit(__doc__)
